/**
 * SHA-256 (FIPS 180-4) in plain TypeScript: no crypto module, so the same code
 * runs in Hermes, the browser and node (tests). Used only as an integrity
 * checksum for backup files, not as a security boundary: anyone can recompute
 * it, so every record is also validated before a restore.
 */

